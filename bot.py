# ==========================================
# Xへ投稿する関数
# ==========================================

def post_to_x(text):
    response = requests.post(
        "https://api.x.com/2/tweets",
        auth=auth,
        json={"text": text},
        timeout=30,
    )

    print("HTTP status:", response.status_code)

    if response.ok:
        print("投稿成功！")
        print(text)
        return True

    print("投稿失敗")
    print(response.text)
    return False


# ==========================================
# メイン処理
# ==========================================

def main():

    now = datetime.now(ZoneInfo("Asia/Tokyo"))
    print("================================")
    print("Riko X Bot 起動")
    print("現在時刻:", now.strftime("%Y-%m-%d %H:%M:%S"))
    print("================================")

    hour = now.hour

    # ------------------------------------------
    # 投稿可能時間
    # ------------------------------------------

    if hour < 9:
        print("現在は投稿時間外です。")
        return

    if hour >= 24:
        print("現在は投稿時間外です。")
        return

    # ------------------------------------------
    # ランダム待機
    #
    # GitHub Actionsが毎時0分に起動しても、
    # 実際の投稿時刻をランダムにずらす。
    #
    # 最大55分待機
    # ------------------------------------------

    wait_seconds = random.randint(0, 55 * 60)

    print(
        "ランダム待機:",
        wait_seconds // 60,
        "分",
        wait_seconds % 60,
        "秒"
    )

    time.sleep(wait_seconds)

    # ------------------------------------------
    # 待機後の現在時刻を再確認
    # ------------------------------------------

    now = datetime.now(ZoneInfo("Asia/Tokyo"))
    hour = now.hour

    print("実際の投稿判定時刻:", now.strftime("%H:%M:%S"))

    # ------------------------------------------
    # 9:00〜20:59
    # 通常投稿
    # ------------------------------------------

    if 9 <= hour <= 20:

        wait_minutes = random.randint(3, 55)
        print(f"あと{wait_minutes}分待って通常投稿します。")
        time.sleep(wait_minutes * 60)
        
        text = random.choice(posts)
        
        print("通常投稿を選択しました。")
        post_to_x(text)
    # ------------------------------------------
    # 21:00〜23:59
    # リンク誘導投稿
    # ------------------------------------------

    if 21 <= hour <= 23:

        text = random.choice(link_posts)
        
        # URLを投稿本文に追加
        text = text + "\n" + LINK_URL
        
        print("リンク投稿を選択しました。")
        post_to_x(text)

    else:
        print("投稿時間外になったため終了します。")


# ==========================================
# 起動
# ==========================================

if __name__ == "__main__":
    main()
